// Writes tools/mcp/war-tools.json: the game tools an MCP seat is offered, generated from
// the same OpenAIAIManager.TOOLS a library seat gets (docs/MCP-ARENA.md). The hub serves
// this file, so a harness that asks for its tools before any WAR page is open still gets
// them all; tests/mcp-hub.test.cjs fails when the file and openai-ai.js disagree.
//
//   node tools/mcp/build-tools.cjs          rewrite the file
//   node tools/mcp/build-tools.cjs --check  exit 1 if it is stale
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(__dirname, 'war-tools.json');

function currentTools() {
    const scope = { console, getCivilization: id => ({ name: id, color: 0xffff00, bonus: { description: 'x' } }) };
    vm.createContext(scope);
    for (const f of ['js/manifest.js', 'js/sha256.js', 'js/conditions.js', 'js/openai-ai.js'])
        vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), scope, { filename: f });
    const M = vm.runInContext('OpenAIAIManager', scope);
    // MCP's tool shape: {name, description, inputSchema}. The JSON round trip leaves the
    // vm's objects behind, so the result compares as plain data.
    const tools = JSON.parse(JSON.stringify(M.TOOLS)).map(t => ({
        name: t.function.name, description: t.function.description, inputSchema: t.function.parameters }));
    return {
        _note: 'Generated by tools/mcp/build-tools.cjs from OpenAIAIManager.TOOLS. Do not edit by hand.',
        maxCommandsPerTurn: M.MAX_COMMANDS_PER_TURN,
        // Tools that do not use a command slot (the plan, as for a library seat).
        free: ['plan'],
        tools
    };
}

function text(o) { return JSON.stringify(o, null, 2) + '\n'; }

if (require.main === module) {
    const want = text(currentTools());
    if (process.argv.includes('--check')) {
        const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
        if (have !== want) { console.error('tools/mcp/war-tools.json is stale: run node tools/mcp/build-tools.cjs'); process.exit(1); }
        console.log('war-tools.json is current');
    } else {
        fs.writeFileSync(OUT, want);
        console.log('wrote', path.relative(ROOT, OUT));
    }
}
module.exports = { currentTools, text, OUT };
