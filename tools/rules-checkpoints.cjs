'use strict';
// The rule checkpoints (b1144): for every version of the rules that was ever pushed, the
// commit that holds it, so the analyzer can replay a match recorded under older rules
// with the files it was played with, fetched from GitHub at that commit.
//
// A version is the pair the transcript's contract records: coreHash (the rule files of
// js/manifest.js, joined) and harnessHash (the harness). Each is listed once, with the
// LAST pushed commit that has it: any commit with the pair runs the same rules, and the
// last one carries the latest replay driver (js/resim.js) that was tested against them.
//
//   node tools/rules-checkpoints.cjs           bring rules/checkpoints.json up to origin/main
//   node tools/rules-checkpoints.cjs --full    read the whole history again
//   node tools/rules-checkpoints.cjs --check   exit 1 if the file is out of date
//
// Run it after pushing a rules change; tests/rules-checkpoints.test.cjs holds every
// shipped sample to it.
const { execFileSync } = require('node:child_process');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), crypto = require('node:crypto');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'rules', 'checkpoints.json');
const REPO = 'asp67/when-agents-rule';
const BRANCH = 'origin/main';           // GitHub serves only what was pushed
const FIRST = '492be8a';                // b954: js/resim.js, the replay driver, exists from here

const git = (...a) => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 28 });
const sha256 = t => crypto.createHash('sha256').update(t, 'utf8').digest('hex');
const lf = s => String(s).replace(/\r\n/g, '\n');

function manifestAt(commit) {
    const ctx = {};
    vm.createContext(ctx);
    vm.runInContext(git('show', commit + ':js/manifest.js') + '\n;globalThis.__m = WarManifest;', ctx);
    return ctx.__m;
}

// The pair a commit's files give, as js/conditions.js computes it in the browser.
function hashesAt(commit) {
    const m = manifestAt(commit);
    return {
        coreHash: sha256(m.rules.map(f => lf(git('show', commit + ':' + f))).join('\n')),
        harnessHash: sha256(lf(git('show', commit + ':' + m.harness))),
    };
}

function buildAt(commit) {
    const html = git('show', commit + ':index.html');
    const m = html.match(/js\/game\.js\?v=(\d+)/);
    return m ? Number(m[1]) : null;
}

// Incremental: an existing index records the last commit it read ("through"), and only
// newer ones are read; --full reads the whole history again.
function generate({ full = false } = {}) {
    const prev = !full && fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : null;
    const from = prev && prev.through ? prev.through : FIRST + '^';
    // Only commits that touched js/ can change the pair.
    const commits = git('rev-list', '--reverse', from + '..' + BRANCH, '--', 'js').trim().split('\n').filter(Boolean);
    const byPair = new Map(((prev && prev.versions) || []).map(v => [v.coreHash + ':' + v.harnessHash, v]));
    for (const c of commits) {
        const h = hashesAt(c);
        byPair.set(h.coreHash + ':' + h.harnessHash, Object.assign(h, {
            commit: c, build: buildAt(c), date: git('log', '-1', '--format=%cs', c).trim() }));
    }
    const versions = [...byPair.values()].sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : (a.build || 0) - (b.build || 0)));
    return { schema: 'war-rules-checkpoints/1', repo: REPO,
        note: 'Generated by tools/rules-checkpoints.cjs: for each version of the rules, the last pushed commit that has it.',
        // The last commit read that could change a version: one that touched js/. Not the
        // branch head, which every push of this file itself would move.
        through: git('rev-list', '-1', BRANCH, '--', 'js').trim() || (prev && prev.through) || null, versions };
}

if (require.main === module) {
    const next = JSON.stringify(generate({ full: process.argv.includes('--full') }), null, 1) + '\n';
    if (process.argv.includes('--check')) {
        const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
        if (now !== next) { console.log('rules/checkpoints.json is out of date: run node tools/rules-checkpoints.cjs'); process.exitCode = 1; }
        else console.log('rules/checkpoints.json is current');
    } else {
        fs.mkdirSync(path.dirname(OUT), { recursive: true });
        fs.writeFileSync(OUT, next);
        console.log('wrote', path.relative(ROOT, OUT), JSON.parse(next).versions.length, 'versions');
    }
}

module.exports = { generate, hashesAt, REPO };
